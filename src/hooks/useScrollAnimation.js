import { useEffect } from 'react';

/**
 * Custom hook to dynamically bind IntersectionObserver to elements with `.reveal-on-scroll`
 * Triggers smooth slide-in and fade animations as the user scrolls.
 */
export function useScrollAnimation(dependency = null) {
  useEffect(() => {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add('is-revealed');
          }
        });
      },
      {
        threshold: 0.12,
        rootMargin: '0px 0px -40px 0px'
      }
    );

    const elements = document.querySelectorAll('.reveal-on-scroll');
    elements.forEach((el) => observer.observe(el));

    return () => {
      elements.forEach((el) => observer.unobserve(el));
    };
  }, [dependency]);
}

