/**
 * Export Utility for UNMESS
 * Converts extracted data into Markdown, Text, JSON, and iCalendar (.ics)
 */

export function exportToMarkdown(data) {
  const { cleanedProse, tasks = [], deadlines = [], reminders = [], ideas = [] } = data;

  let md = `# UNMESS Summary & Action Plan\n`;
  md += `*Generated by UNMESS on ${new Date().toLocaleString()}*\n\n`;

  if (cleanedProse) {
    md += `## 📋 Synthesized Clarity\n${cleanedProse}\n\n`;
  }

  if (tasks.length > 0) {
    md += `## ✅ Action Items & Tasks\n`;
    tasks.forEach((t) => {
      const check = t.completed ? '[x]' : '[ ]';
      const prio = t.priority ? `**[${t.priority}]** ` : '';
      const time = t.estimatedTime ? ` *(Est: ${t.estimatedTime})*` : '';
      const dl = t.deadline ? ` ⏳ Due: ${t.deadline}` : '';
      md += `- ${check} ${prio}${t.title}${time}${dl}\n`;
      if (t.description && t.description !== t.title) {
        md += `  > ${t.description}\n`;
      }
    });
    md += `\n`;
  }

  if (deadlines.length > 0) {
    md += `## ⏰ Critical Deadlines\n`;
    deadlines.forEach((d) => {
      md += `- **${d.deadlineText}**: ${d.title}\n`;
    });
    md += `\n`;
  }

  if (reminders.length > 0) {
    md += `## 🔔 Reminders\n`;
    reminders.forEach((r) => {
      md += `- 📌 ${r.text || r.title}\n`;
    });
    md += `\n`;
  }

  if (ideas.length > 0) {
    md += `## 💡 Creative Sparks & Ideas\n`;
    ideas.forEach((i) => {
      md += `- **${i.title}**: ${i.details || ''}\n`;
    });
    md += `\n`;
  }

  return md;
}

export function exportToPlainText(data) {
  const { cleanedProse, tasks = [], deadlines = [] } = data;
  let text = `UNMESS - Action Plan (${new Date().toLocaleDateString()})\n`;
  text += `==============================================\n\n`;

  if (cleanedProse) {
    text += `SYNTHESIS:\n${cleanedProse}\n\n`;
  }

  text += `TASKS:\n`;
  tasks.forEach((t, i) => {
    text += `${i + 1}. [${t.priority || 'P3'}] ${t.title} ${t.deadline ? `(Due: ${t.deadline})` : ''}\n`;
  });

  return text;
}

export function exportToICS(tasks, deadlines) {
  // Generate iCalendar standard format
  const now = new Date();
  const formatICSDate = (d) => {
    return d.toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
  };

  let ics = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//UNMESS//Clarity Engine//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
  ];

  const items = deadlines && deadlines.length > 0 ? deadlines : tasks;

  items.forEach((item, index) => {
    const start = new Date(now.getTime() + (index + 1) * 3600 * 1000);
    const end = new Date(start.getTime() + 3600 * 1000);

    ics.push('BEGIN:VEVENT');
    ics.push(`UID:unmess-${Date.now()}-${index}@unmess.app`);
    ics.push(`DTSTAMP:${formatICSDate(now)}`);
    ics.push(`DTSTART:${formatICSDate(start)}`);
    ics.push(`DTEND:${formatICSDate(end)}`);
    ics.push(`SUMMARY:${item.title || item.deadlineText || 'UNMESS Task'}`);
    ics.push(`DESCRIPTION:${item.description || item.deadlineText || 'Organized by UNMESS'}`);
    ics.push('STATUS:CONFIRMED');
    ics.push('END:VEVENT');
  });

  ics.push('END:VCALENDAR');
  return ics.join('\r\n');
}

export function downloadFile(content, filename, contentType) {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

